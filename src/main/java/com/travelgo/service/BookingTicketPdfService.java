package com.travelgo.service;

import com.itextpdf.kernel.colors.DeviceRgb;
import com.itextpdf.kernel.pdf.PdfDocument;
import com.itextpdf.kernel.pdf.PdfWriter;
import com.itextpdf.layout.Document;
import com.itextpdf.layout.element.Cell;
import com.itextpdf.layout.element.Paragraph;
import com.itextpdf.layout.element.Table;
import com.itextpdf.layout.properties.TextAlignment;
import com.itextpdf.layout.properties.UnitValue;
import com.travelgo.entity.Booking;
import com.travelgo.entity.BookingHotel;
import com.travelgo.entity.Traveler;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.time.format.DateTimeFormatter;
import java.util.List;

@Service
public class BookingTicketPdfService {

    public byte[] createTicket(Booking booking, List<Traveler> travelers, BookingHotel hotel) {
        ByteArrayOutputStream output = new ByteArrayOutputStream();
        PdfWriter writer = new PdfWriter(output);
        PdfDocument pdf = new PdfDocument(writer);
        try (Document document = new Document(pdf)) {
            DeviceRgb green = new DeviceRgb(5, 150, 105);
            DeviceRgb navy = new DeviceRgb(15, 23, 42);

            document.add(new Paragraph("TravelGO E-Ticket & Booking Voucher")
                    .setFontSize(22).setBold().setFontColor(navy).setTextAlignment(TextAlignment.CENTER));
            document.add(new Paragraph("CONFIRMED & ISSUED")
                    .setFontSize(11).setBold().setFontColor(green).setTextAlignment(TextAlignment.CENTER));
            document.add(new Paragraph("Booking reference: TG-" + booking.getId())
                    .setTextAlignment(TextAlignment.CENTER).setMarginBottom(20));

            Table details = new Table(UnitValue.createPercentArray(new float[]{1, 2})).useAllAvailableWidth();
            addRow(details, "Customer", booking.getUser().getName());
            addRow(details, "Package", booking.getTourPackage().getName());
            addRow(details, "Destination", booking.getTourPackage().getDestination().getCity() + ", "
                    + booking.getTourPackage().getDestination().getCountry());
            addRow(details, "Travel date", booking.getTravelDate().format(DateTimeFormatter.ofPattern("dd MMM yyyy")));
            addRow(details, "Duration", booking.getTourPackage().getDurationDays() + " days");
            addRow(details, "Travelers", String.valueOf(booking.getNumberOfTravelers()));
            addRow(details, "Amount paid", "$" + booking.getTotalPackageAmount());
            addRow(details, "Flight details", valueOrFallback(booking.getTourPackage().getFlightDetails(), "See final itinerary at check-in"));
            document.add(details);

            if (hotel != null) {
                document.add(new Paragraph("Accommodation").setBold().setFontSize(15).setMarginTop(18));
                document.add(new Paragraph(hotel.getHotel().getName() + " | " + hotel.getCheckInDate()
                        + " to " + hotel.getCheckOutDate() + " | " + hotel.getNumberOfRooms() + " room(s)"));
            }

            document.add(new Paragraph("Passenger details").setBold().setFontSize(15).setMarginTop(18));
            if (travelers == null || travelers.isEmpty()) {
                document.add(new Paragraph("Lead passenger: " + booking.getUser().getName()));
            } else {
                Table passengerTable = new Table(UnitValue.createPercentArray(new float[]{2, 1, 1})).useAllAvailableWidth();
                passengerTable.addHeaderCell("Passenger");
                passengerTable.addHeaderCell("Passport");
                passengerTable.addHeaderCell("Nationality");
                for (Traveler traveler : travelers) {
                    passengerTable.addCell(traveler.getFullName());
                    passengerTable.addCell(traveler.getPassportNumber());
                    passengerTable.addCell(traveler.getNationality());
                }
                document.add(passengerTable);
            }

            document.add(new Paragraph("Check-in instructions").setBold().setFontSize(15).setMarginTop(18));
            document.add(new Paragraph("Arrive at the international terminal at least 3 hours before departure. Present this PDF and each traveler's original passport at check-in."));
            document.add(new Paragraph("Generated by TravelGO • Keep this document with your travel records")
                    .setFontSize(9).setFontColor(new DeviceRgb(100, 116, 139)).setMarginTop(24)
                    .setTextAlignment(TextAlignment.CENTER));
        }
        return output.toByteArray();
    }

    private void addRow(Table table, String label, String value) {
        table.addCell(new Cell().add(new Paragraph(label).setBold()));
        table.addCell(new Cell().add(new Paragraph(valueOrFallback(value, "Not provided"))));
    }

    private String valueOrFallback(String value, String fallback) {
        return value == null || value.isBlank() ? fallback : value;
    }
}
